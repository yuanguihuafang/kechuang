def build_smart_qa_field_extraction_system(
    *,
    draft_type: str,
    allow_multiple: bool,
    field_guide: str,
    required_labels: str,
    inquiry_guidance: str = "",
    draft_only: bool = True,
) -> str:
    label, focus = FIELD_EXTRACTION_PROFILES.get(
        draft_type, ("当前资料", "只提取当前资料类型对应字段。")
    )
    field_prompt = (
        SMART_QA_FIELD_PROMPTS.get(draft_type, field_guide) if draft_only else field_guide
    )
    if isinstance(field_prompt, tuple):
        field_prompt = "；".join(field_prompt)
    multiple = (
        "当前资料允许多条记录：每条独立记录必须单独放入 items 数组，每项结构相同，"
        "格式为 {items:[{title,fields,summary,missing_fields,optional_questions,confidence}]}；"
        "只有确认只有一条记录时才返回单条对象。"
        if allow_multiple
        else ""
    )
    return (
        "一切以准确和可用为先，直接抽取并返回结果，不展示思考过程，不做无依据的长篇分析。"
        f"prompt_version:{SMART_QA_FIELD_EXTRACTION_PROMPT_VERSION}。你是{label}字段提取器。"
        "只能依据用户描述和上传资料抽取，不补造事实。"
        "根据用户当前消息和上下文按语义提取已明确提供的字段，不要拘泥于固定表述，也不要重复追问已提供的信息。"
        f"{focus}只能提取当前{label}字段，不要输出其他知识库字段。"
        f"{multiple}只输出 JSON，字段为 title、fields、summary、missing_fields、"
        "optional_questions、confidence。fields 使用给定的 MySQL 物理字段名；缺失信息不要猜测。"
        'JSON 结构示例：{"title":"名称","fields":{},"summary":"摘要",'
        '"missing_fields":[],"optional_questions":[],"confidence":0.5}；'
        "示例仅说明结构，fields 必须填写实际提取的业务字段。"
        "每个字段只保留最准确的一项值，数值、日期、单位、型号和专有名词必须按原文保留。"
        "各字段必须严格按字段语义填写，字段之间不要重复；描述字段只保留该字段对应的事实和内容片段，"
        "禁止把整篇解析原文、整页文字或所有字段拼接进描述字段，无法确认归属时留空。"
        "analyse_contect（分析）必须由模型基于文档事实主动归纳生成，不能复制原文、summary或其它字段；"
        "没有足够事实进行分析时留空。summary仅作整体摘要，不能自动填充任何业务字段。"
        "每个 fields 字段值和 summary 最多 3060 个字符；超过时压缩为完整摘要，不要输出整篇原文或重复内容。除非图片 URL 明确跟在头像、照片、图片或 Logo 等字段标签后，否则不要输出图片 URL；明确归属时按原文保留 URL。"
        f"当前字段（中文名、物理字段名和要求）：{field_prompt}；无法确认或可能不准确就留空。"
        f"当前草稿类型的必填字段（中文展示名）是：{required_labels}。"
        "missing_fields 只能使用这些中文展示名，不要输出英文字段名。"
        "企业名称、联系人、联系电话若用户资料中已有，仅在用户没有明确说出时使用；不要编造。"
        "信息不足只针对当前流程真正缺少的关键内容提出 optional_questions，最多 3 个；已有名称、描述或明确业务内容时不要判定为信息不全，"
        "优先围绕需求描述、使用场景、目标、预算、周期以及用户明确提到的产品或行业上下文追问，"
        "企业名称、联系人、联系电话优先使用当前用户登记资料；用户在当前对话中明确提供新值时，以用户明确提供的值覆盖登记资料。只有登记资料和对话都没有时，才提示用户稍后补充，不要连续追问。"
        "但需求分析由模型根据已有对话和资料总结，不要追问需求分析。"
        "如果用户提到具体产品、行业或对象，问题必须围绕该上下文展开，例如提到飞机就追问飞机相关的应用环节、"
        "技术问题或目标，不要套用固定问题列表。已明确提供的信息不要重复询问；必填字段已经齐全时返回空数组。"
        f"{inquiry_guidance}"
    )
