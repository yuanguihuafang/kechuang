"""网关运行时服务契约：只声明路由需要的最小能力。"""

from __future__ import annotations

from typing import Any, Protocol

from core.contracts.agent import Agent
from core.contracts.tools import ToolContext


class FileWorkflow(Protocol):
    async def upload(self, file: Any, **kwargs: Any) -> dict[str, Any]: ...
    async def parse(self, task_id: str) -> dict[str, Any]: ...
    async def confirm(self, task_id: str, **kwargs: Any) -> dict[str, Any]: ...
    def status(self, task_id: str) -> dict[str, Any] | None: ...
    def resume(self, task_id: str) -> dict[str, Any] | None: ...


class GatewayAgentEndpoint(Protocol):
    """挂载到唯一 FastAPI 网关的进程内 Agent 端点。"""

    agent: Agent
    app: Any
    metrics: Any

    async def readiness_checks(self) -> dict[str, dict[str, str]]: ...

    def configure_task_store(self, store: TaskStore) -> None: ...

    def configure_task_runner(self, runner: TaskRunner) -> None: ...


class RetrievalAgentEndpoint(GatewayAgentEndpoint, Protocol):
    """检索端点额外拥有 Milvus worker 级资源的关闭职责。"""

    def close(self) -> None: ...


class TaskStore(Protocol):
    def create(self, *, operation: str, status: str, **fields: Any) -> dict[str, Any]: ...
    def get(self, task_id: str) -> dict[str, Any] | None: ...
    def update(self, task_id: str, **fields: Any) -> dict[str, Any] | None: ...
    def claim_next(
        self, *, worker_id: str, operations: set[str], lease_seconds: int = 120
    ) -> dict[str, Any] | None: ...
    def claim(
        self, task_id: str, *, worker_id: str, lease_seconds: int = 120
    ) -> dict[str, Any] | None: ...
    def requeue_expired(self) -> int: ...
    def interrupt_claim(self, task_id: str, *, worker_id: str) -> bool: ...
    def renew_lease(self, task_id: str, *, worker_id: str, lease_seconds: int = 120) -> bool: ...
    def list(self, **kwargs: Any) -> list[dict[str, Any]]: ...
    def list_page(self, **kwargs: Any) -> dict[str, Any]: ...
    def count_by_status(self) -> dict[str, int]: ...


class TaskRunner(Protocol):
    def register(self, operation: str, handler: Any) -> None: ...
    def start(self, *, poll_seconds: float = 1.0) -> None: ...
    async def stop(self) -> None: ...


class ToolAdapter(Protocol):
    async def delete_document(self, arguments: dict[str, Any]) -> dict[str, Any]: ...
    async def search_knowledge(
        self,
        arguments: dict[str, Any],
        *,
        context: ToolContext | dict[str, Any] | None = None,
    ) -> dict[str, Any]: ...


